const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const shifts = [false, false, true].map(disabled => ({checked:false, disabled, dataset:{summary:'Turno <texto>'}, addEventListener(name, fn){this.change=fn;}}));
const list = {items:[], replaceChildren(){this.items=[];}, append(item){this.items.push(item);}};
const count = {textContent:''}, acceptance = {checked:false};
const planner = {querySelectorAll(){return shifts;}, querySelector(selector){return {'[data-selection-count]':count,'[data-selection-list]':list,'[data-shift-accept]':acceptance}[selector];}};
const source=fs.readFileSync('app/static/js/professional-shifts.js','utf8');
vm.runInNewContext(source,{document:{querySelector(){return planner;},createElement(){return {textContent:''};}}});
assert.match(count.textContent,/^0 /);
shifts[0].checked=true;shifts[0].change();
shifts[1].checked=true;shifts[1].change();
assert.match(count.textContent,/^2 /);
assert.equal(list.items.length,2);
assert.equal(list.items[0].textContent,'Turno <texto>');
acceptance.checked=true;shifts[0].checked=false;shifts[0].change();
assert.equal(acceptance.checked,false);
assert.match(count.textContent,/^1 /);
shifts[2].checked=true;shifts[2].change();
assert.equal(list.items.length,1);
vm.runInNewContext(source,{document:{querySelector(){return null;}}});
console.log('PASS production controller: summary, deselection, disabled blocks, acceptance reset, absent planner');
