    def test_descending_owned_sequence_is_normalized_before_insert(self):
        self._create_partial(
            generator="owned_sequence",
            sequence_options=(
                "AS INTEGER INCREMENT BY -1 MINVALUE 1 MAXVALUE 100 "
                "START WITH 100 NO CYCLE"
            ),
        )
        actor_id = self._insert_user("descending")
        self._insert_command_with_id(actor_id, 49, "pg-descending-0049")
        self._insert_command_with_id(actor_id, 50, "pg-descending-0050")
        with self.engine.begin() as connection:
            connection.execute(
                sa.text(
                    "SELECT setval('operation_commands_existing_seq', 50, true)"
                )
            )

        before = self._sequence_parameters()
        self.assertEqual(before["increment_by"], -1)
        self.assertEqual(before["effective_next"], 49)

        self._alembic("upgrade", "20260726_02")

        after = self._sequence_parameters()
        self.assertEqual(after["increment_by"], 1)
        self.assertEqual(after["min_value"], 1)
        self.assertEqual(after["max_value"], 2147483647)
        self.assertFalse(after["cycle"])
        self.assertEqual(after["effective_next"], 51)
        self.assertEqual(
            self._insert_command_without_id(actor_id, "pg-descending-fixed"),
            51,
        )

